#!/usr/bin/env bash
# ==============================================================================
# سكربت بناء ملف ويندوز التنفيذي (.exe) على نظام لينكس مينت (Linux Mint)
# مُعد خصيصاً للتوافق مع مواصفات جهاز AMD A4-9125 لتقليل الضغط وسرعة البناء
# ==============================================================================

set -e

echo "=========================================================="
echo "🚀 بدء تجهيز وبناء تطبيق CAD Studio لنظام Windows (.exe)"
echo "🖥️ بيئة التشغيل الحالية: Linux Mint"
echo "=========================================================="

# 1. ضبط حدود استهلاك الذاكرة لتناسب معالجات AMD الثنائية النواة
export NODE_OPTIONS="--max-old-space-size=2048"

# 2. التأكد من تثبيت الحزم
if [ ! -d "node_modules" ]; then
    echo "📦 جاري تثبيت حزم الاعتماديات..."
    npm install --legacy-peer-deps
fi

# 3. بناء تطبيق React / Vite أولاً
echo "⚙️ [1/2] تجميع ملفات الويب والواجهة (Vite Build)..."
npm run build

# 4. بناء ملف Windows التنفيذي
echo "📦 [2/2] جاري توليد ملف Windows EXE عبر electron-builder..."

# اختيار النمط: افتراضياً Portable لسرعة البناء بدون ضغط NSIS الشاق
if [ "$1" == "nsis" ]; then
    echo "🔨 النمط المختار: مثبت التثبيت الرسمي (NSIS Setup Installer)"
    npm run build:win
elif [ "$1" == "dir" ]; then
    echo "⚡ النمط المختار: مجلد تنفيذي فوري سريع (Unpacked Directory)"
    npm run build:win:fast
else
    echo "✨ النمط المختار: ملف تنفيذي محمول مستقل (Portable .exe)"
    npm run build:win:portable
fi

echo "=========================================================="
echo "✅ تم البناء بنجاح!"
echo "📁 تجد الملفات الناتجة داخل المجلد: ./dist-electron"
echo "=========================================================="
